import { describe, expect, it, vi } from "vitest";
import { generateMarkdownReport } from "../cli/formatting/report.js";
import { displayReview } from "../cli/formatting/review.js";
import type { VectorStore } from "../store.js";
import type { Cluster, ScoredPR } from "../types.js";

describe("cli/formatting/review", () => {
  it("formats review outputs correctly", () => {
    const logSpy = vi.spyOn(console, "log").mockImplementation(() => {});

    displayReview(
      123,
      "Fix race condition in queue",
      {
        summary: "Good fix for async queue",
        concerns: ["Needs timeout handling"],
        recommendation: "merge",
        confidence: 0.95,
      },
      {
        author: "alice",
        additions: 10,
        deletions: 2,
        provider: "openai",
        model: "gpt-4o",
      },
    );

    expect(logSpy).toHaveBeenCalled();
    const output = logSpy.mock.calls.map((c) => c.join(" ")).join("\n");
    expect(output).toContain("#123");
    expect(output).toContain("Fix race condition in queue");
    expect(output).toContain("Author: alice");
    expect(output).toContain("Reviewed with openai/gpt-4o");
    expect(output).toContain("Summary:");
    expect(output).toContain("Good fix for async queue");
    expect(output).toContain("Concerns:");
    expect(output).toContain("Needs timeout handling");
    expect(output).toContain("MERGE");
    expect(output).toContain("95%");

    logSpy.mockRestore();
  });
});

describe("cli/formatting/report", () => {
  it("generates markdown report with tables and sections", () => {
    const mockItem1: ScoredPR = {
      repo: "test-owner/test-repo",
      number: 101,
      title: "Improve caching layer",
      body: "Adds redis cache",
      author: "bob",
      state: "open",
      createdAt: "2026-01-01T00:00:00Z",
      updatedAt: "2026-01-02T00:00:00Z",
      labels: [],
      score: 8.5,
      signals: {
        hasTests: 1,
        ciPassing: 1,
        diffSize: 1,
        authorHistory: 1,
        descriptionQuality: 1,
        reviewApprovals: 1,
      },
      type: "pr",
      hasTests: true,
      ciStatus: "success",
      reviewCount: 2,
      additions: 50,
      deletions: 10,
    };

    const mockItem2: ScoredPR = {
      repo: "test-owner/test-repo",
      number: 102,
      title: "Fix cache invalidation bug",
      body: "Invalidate properly",
      author: "carol",
      state: "open",
      createdAt: "2026-01-01T12:00:00Z",
      updatedAt: "2026-01-02T12:00:00Z",
      labels: [],
      score: 7.2,
      signals: {
        hasTests: 0,
        ciPassing: 1,
        diffSize: 1,
        authorHistory: 1,
        descriptionQuality: 1,
        reviewApprovals: 0.5,
      },
      type: "pr",
      hasTests: false,
      ciStatus: "success",
      reviewCount: 1,
      additions: 20,
      deletions: 5,
    };

    const mockCluster: Cluster = {
      id: 1,
      theme: "Cache improvements and invalidation",
      items: [mockItem1, mockItem2],
      avgSimilarity: 0.91,
      minSimilarity: 0.88,
      bestPick: mockItem1,
    };

    const mockStore = {
      getEmbedding: vi.fn().mockReturnValue(new Float32Array([1, 0, 0])),
    } as unknown as VectorStore;

    const report = generateMarkdownReport({
      repoFull: "test-owner/test-repo",
      date: "2026-10-26",
      stats: { totalItems: 2, prs: 2, issues: 0 },
      clusters: [mockCluster],
      ranked: [{ number: 101, score: 8.5, author: "bob", title: "Improve caching layer" }],
      visionResults: { aligned: 1, drifting: 1, offVision: 0 },
      topN: 10,
      clusterN: 10,
      verbose: true,
      store: mockStore,
    });

    expect(report).toContain("# pr-prism triage report");
    expect(report).toContain("**repo:** test-owner/test-repo");
    expect(report).toContain("## overview");
    expect(report).toContain("| open PRs scanned | 2 |");
    expect(report).toContain("## duplicate clusters (top 10)");
    expect(report).toContain("[#101](https://github.com/test-owner/test-repo/pull/101)");
    expect(report).toContain("## cluster details");
    expect(report).toContain("## top 10 ranked PRs");
    expect(report).toContain("## vision alignment");
    expect(report).toContain("*generated by [pr-prism](https://github.com/StressTestor/pr-prism)*");
  });
});
